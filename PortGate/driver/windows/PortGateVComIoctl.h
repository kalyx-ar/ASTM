#pragma once
#include <winioctl.h>
// Optional, out-of-band API for aware applications. Ordinary serial payload is never changed.
#define IOCTL_PORTGATE_VCOM_STATE CTL_CODE(FILE_DEVICE_SERIAL_PORT,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define IOCTL_PORTGATE_VCOM_COMPLETE_TASK CTL_CODE(FILE_DEVICE_SERIAL_PORT,0x801,METHOD_BUFFERED,FILE_WRITE_ACCESS)
#define IOCTL_PORTGATE_VCOM_WAIT_STATE CTL_CODE(FILE_DEVICE_SERIAL_PORT,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define PORTGATE_VCOM_VERSION 1
typedef struct PORTGATE_VCOM_STATUS {
    ULONG Version;
    ULONG State; // 0 offline, 1 online, 2 retirement pending
    ULONGLONG WarningId;
    WCHAR Reason[256];
} PORTGATE_VCOM_STATUS;
